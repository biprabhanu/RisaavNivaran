"""Write ../numbers.tex: LaTeX macros for every engine/evaluation number used on the slides.
Source: numbers.json (compute_numbers.py) and evaluation_numbers.json (scenarios.run_evaluation, seed 2026, 25 scenarios).
Run: python3 gen_macros.py"""
import json, os
H = os.path.dirname(os.path.abspath(__file__))
N = json.load(open(os.path.join(H, "numbers.json"))); E = json.load(open(os.path.join(H, "evaluation_numbers.json")))
P = {p["policy_id"]: p for p in E["policies"]}; A = {a["id"]: a for a in N["actions"]}
rs = r"\rupee{}"
def inr(x): return rs + f"{x:,.0f}"
def k(x): return rs + f"{x/1000:,.0f}k"
m = {
 "Hprior": f"{N['entropy']:.2f}", "Hfault": f"{N['fault_found']['entropy_after']:.2f}", "Lambda": inr(N["lambda"]),
 "PriorW": f"{N['prior']['waste_surface']*100:.0f}", "PriorG": f"{N['prior']['gas_collection']*100:.0f}", "PriorF": f"{N['prior']['flare']*100:.0f}",
 "Pfault": f"{N['fault_found']['p']:.2f}",
 "PostW": f"{N['fault_found']['posterior']['waste_surface']*100:.0f}", "PostG": f"{N['fault_found']['posterior']['gas_collection']*100:.0f}",
 "PostF": f"{N['fault_found']['posterior']['flare']*100:.0f}", "NoFaultW": f"{N['no_fault']['posterior']['waste_surface']*100:.0f}",
 "PreLow": f"{N['verification']['pre_low']:,.0f}", "PreHigh": f"{N['verification']['pre_high']:,.0f}",
 "PostLow": f"{N['verification']['post_low']:,.0f}", "PostHigh": f"{N['verification']['post_high']:,.0f}",
 "Threshold": f"{N['verification']['threshold']:,.0f}",
 "SensStab": f"{E['sensitivity']['top_action_stability_pct']:.0f}", "SensTau": f"{E['sensitivity']['mean_kendall_tau']:.3f}",
 "SensDraws": f"{E['sensitivity']['n_draws']}", "SensFC": f"{E['sensitivity']['c_false_closures_perturbed']}",
 "SensInsp": f"{E['sensitivity']['c_inspections_per_resolved_perturbed']:.2f}", "Seed": f"{E['seed']}", "Nscen": f"{E['n']}",
}
for key, aid in [("Rec", "records_request"), ("Ogi", "ogi_survey"), ("Gnd", "ground_survey"), ("Sat", "satellite_wait")]:
    a = A[aid]
    m[f"Eig{key}"] = f"{a['eig']:.2f}"; m[f"Cost{key}"] = inr(a["cost"]); m[f"CostK{key}"] = k(a["cost"]) if a["cost"] else rs + "0"
    m[f"Days{key}"] = f"{a['time']:.0f}"; m[f"Gain{key}"] = "--" if a["gain_per_10k"] is None else f"{a['gain_per_10k']:.2f}"
    m[f"Rank{key}"] = str(a["rank"])
for key, pid in [("A", "A"), ("B", "B"), ("C", "C"), ("X", "C_noplan")]:
    p = P[pid]
    m[f"FC{key}"] = f"{p['false_closures']}/{p['n_cases']}"; m[f"Res{key}"] = str(p["resolved_cases"])
    m[f"Attr{key}"] = f"{p['correct_attribution_rate']*100:.0f}\\%"; m[f"SrcInsp{key}"] = f"{p['attribution_inspections_per_case']:.2f}"
    m[f"Insp{key}"] = f"{p['inspections_per_resolved']:.2f}"; m[f"Cost{key}Pol"] = inr(p["cost_per_resolved_inr"])
    m[f"Stake{key}"] = f"{p['mean_days_to_stakeholder']:.0f}"; m[f"Trace{key}"] = f"{p['traceability_pct']:.1f}\\%".replace(".0\\%", "\\%")
    m[f"Close{key}"] = f"{p['mean_days_to_closure']:.1f}"
with open(os.path.join(os.path.dirname(H), "numbers.tex"), "w") as f:
    f.write("% AUTO-GENERATED by src/gen_macros.py from the engine's computed numbers. Do not edit by hand.\n")
    for kk, v in m.items(): f.write(f"\\newcommand{{\\n{kk}}}{{{v}}}\n")
print(open(os.path.join(os.path.dirname(H), "numbers.tex")).read())
